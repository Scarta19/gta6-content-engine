"""Asset registry with mandatory provenance. Unlicensed media cannot enter a render."""

from __future__ import annotations

import hashlib
import sqlite3
from pathlib import Path

from gce import db

LICENSES = {
    "owned": "Created by us (screen recordings of our own play, our own graphics).",
    "licensed": "Paid or written license from the rights holder. Keep the license reference.",
    "permitted": "Explicit written permission from the creator. provenance_url must point to it.",
    "press_kit": "Official press/media kit made available for editorial use. Check its terms.",
    "ai_generated": "Generated by us with an AI tool (e.g. Higgsfield). Always labeled on screen.",
}
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".webp"}
VIDEO_EXT = {".mp4", ".mov", ".webm", ".mkv"}
AUDIO_EXT = {".mp3", ".wav", ".m4a", ".ogg"}


def kind_of(path: Path) -> str:
    ext = path.suffix.lower()
    if ext in IMAGE_EXT:
        return "image"
    if ext in VIDEO_EXT:
        return "video"
    if ext in AUDIO_EXT:
        return "audio"
    raise ValueError(f"unsupported asset type: {ext}")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def add(
    conn: sqlite3.Connection,
    path: Path,
    license: str,
    source: str,
    provenance_url: str = "",
    notes: str = "",
) -> int:
    if license not in LICENSES:
        raise ValueError(f"license must be one of: {', '.join(LICENSES)}")
    if not path.exists():
        raise FileNotFoundError(path)
    if license in ("permitted", "licensed", "press_kit") and not provenance_url:
        raise ValueError(f"license '{license}' requires --provenance-url (permission/license link)")
    if not source.strip():
        raise ValueError("source is required (who made it / where it came from)")
    cur = conn.execute(
        "INSERT INTO assets (path, kind, license, source, provenance_url, ai_generated, sha256,"
        " notes, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (
            str(path.resolve()),
            kind_of(path),
            license,
            source,
            provenance_url,
            int(license == "ai_generated"),
            sha256(path),
            notes,
            db.now(),
        ),
    )
    assert cur.lastrowid is not None
    return cur.lastrowid


def attach(conn: sqlite3.Connection, script_id: int, asset_ids: list[int]) -> None:
    conn.execute("DELETE FROM script_assets WHERE script_id = ?", (script_id,))
    for pos, asset_id in enumerate(asset_ids):
        conn.execute(
            "INSERT INTO script_assets (script_id, asset_id, position) VALUES (?, ?, ?)",
            (script_id, asset_id, pos),
        )


def for_script(conn: sqlite3.Connection, script_id: int) -> list[sqlite3.Row]:
    return conn.execute(
        "SELECT a.* FROM assets a JOIN script_assets sa ON sa.asset_id = a.id"
        " WHERE sa.script_id = ? ORDER BY sa.position",
        (script_id,),
    ).fetchall()
